
# Video Requirements

# • Resolution: 1920 x 1080 pixels
# • Aspect Ratio: 16:9
# • Frame Rate / Format: 1080i/25 (25fps interlaced)
# • Color Sub-sampling: 4:2:2
# • Luminance & RGB Range: RGB components within -5% to 105%; luminance within -1% to 103%
# • Codec: AVC-Intra 100Mbit/s
# • File Container: Single MXF OP1a file conforming to the AS-11 UK DPP HD shim

# Audio Requirements

# • Loudness (EBU R128): Target programme loudness of -23.0 LUFS (±1.0 LU for non-live, ±2.0 LU for live)
# • True Peak Limit: Maximum -1 dBTP
# • Format: PCM 48 kHz / 24-bit audio

#Timecode and Leader. Standard file delivery uses a 10:00:00:00 programme start timecode, preceded by line-up bars/tone and a programme slate/clock


